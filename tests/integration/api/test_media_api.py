async def test_judge_routes_expose_ground_truth(client, settings, media_root):
    expected = {"event_type": "test_event", "region": "blind_zone_02", "t_event_s": 8.4}
    (settings.prepared_dir / "scenario_001").mkdir(parents=True)
    (settings.prepared_dir / "scenario_001" / "expected.json").write_text(json.dumps(expected))

    judge = (await client.get("/api/judge/scenarios/scenario_001")).json()
    assert judge["judge_only"] is True
    assert judge["ground_truth_camera"]["id"] == "cam_gt"
    assert judge["ground_truth_camera"]["video_url"] == "/api/judge/scenarios/scenario_001/video"
    assert judge["ground_truth_camera"]["video_available"] is True
    assert judge["expected"] == expected

    gt_bytes = (media_root / "data/prepared/scenario_001/hidden_ground_truth.mp4").read_bytes()
    full = await client.get(judge["ground_truth_camera"]["video_url"])
    assert full.status_code == 200 and full.content == gt_bytes
    ranged = await client.get(
        judge["ground_truth_camera"]["video_url"], headers={"Range": "bytes=10-19"}
    )
    assert ranged.status_code == 206
    assert ranged.headers["content-range"] == f"bytes 10-19/{len(gt_bytes)}"
    assert (await client.get("/api/judge/scenarios/nope")).status_code == 404


