async def test_frame_route_rejects_traversal_and_ground_truth(
    client, start_run, read_events, settings, make_jpeg
):
    """Each traversal URL has a real JPEG planted where it would resolve, so a missing
    guard shows up as a 200 rather than an accidental 404. Starlette decodes ``%2E``
    and ``%5C`` into path params, so ``..`` and backslashes do reach the handler."""
    run_id = (await start_run())["run_id"]
    await read_events(run_id)
    runs, run_dir = settings.runs_dir, settings.runs_dir / run_id
    base = f"/media/runs/{run_id}/frames"
    planted = {
        f"{base}/cam_gt/0.jpg": (run_dir / "frames/cam_gt/0000.jpg", {403}),
        # camera_id ".." -> <run_dir>/frames/../0000.jpg
        f"{base}/%2E%2E/0.jpg": (run_dir / "0000.jpg", {404}),
        # backslashes separate on Windows: climbs to <runs>/x
        f"{base}/..%5C..%5Cx/0.jpg": (runs / "x/0000.jpg", {404}),
        # escapes the runs dir entirely
        f"{base}/..%5C..%5C..%5Coutside/0.jpg": (runs.parent / "outside/0000.jpg", {404}),
        # run_id ".." with a planted run.json one level above the runs dir
        "/media/runs/%2E%2E/frames/cam_01/0.jpg": (runs.parent / "frames/cam_01/0000.jpg", {404}),
    }
    (runs.parent / "run.json").write_text(json.dumps({"scenario_id": "scenario_001"}))
    for url, (target, allowed) in planted.items():
        make_jpeg(target)
        response = await client.get(url)
        assert response.status_code in allowed, (url, response.status_code)
        assert not re.match(rb"^\xff\xd8", response.content), f"image served for {url}"

    for url, allowed in {
        f"{base}/..%2F..%2Fx/0.jpg": {404},
        f"{base}/cam_01/-1.jpg": {422},
        f"{base}/cam_01/abc.jpg": {422},
        "/media/runs/run_unknown/frames/cam_01/0.jpg": {404},
    }.items():
        assert (await client.get(url)).status_code in allowed, url


async def test_frame_route_refuses_symlink_escape(
    client, start_run, read_events, settings, tmp_path, make_jpeg
):
    run_id = (await start_run())["run_id"]
    await read_events(run_id)
    outside = tmp_path / "outside_frames"
    make_jpeg(outside / "0000.jpg")
    link = settings.runs_dir / run_id / "frames" / "cam_01"
    shutil.rmtree(link, ignore_errors=True)  # the run sampled real frames here
    link.parent.mkdir(parents=True, exist_ok=True)
    try:
        link.symlink_to(outside, target_is_directory=True)
    except OSError:
        if sys.platform != "win32":
            raise
        import _winapi  # unprivileged fallback: a directory junction

        _winapi.CreateJunction(str(outside), str(link))
    response = await client.get(f"/media/runs/{run_id}/frames/cam_01/0.jpg")
    assert response.status_code == 404
